    /// Run an in-process sub-agent and return a [crate::tools::ToolResult].
    ///
    /// If output_schema is given, the sub-agent is instructed to return a JSON
    /// value conforming to that schema, and the result carries that JSON
    /// (pretty-printed), or a structured error if the output does not parse.
    /// Without a schema, it returns the sub-agent's final free-text output.
    pub(crate) async fn run_subagent(
        &self,
        task: &str,
        output_schema: Option<&serde_json::Value>,
        fork: bool,
    ) -> crate::tools::ToolResult {
        let effective_task = match output_schema {
            Some(schema) => format!(
                "{}\n\n[STRUCTURED OUTPUT]\nReturn your final answer as a single JSON value conforming to this JSON Schema. Do NOT wrap it in markdown code fences and do NOT add any other prose. Return ONLY the JSON value as your final message.\n\n{}\n",
                task, schema
            ),
            None => task.to_string(),
        };
        match self.spawn_subagent_session(&effective_task, fork).await {
            Ok((id, text)) => {
                if output_schema.is_some() {
                    match Self::extract_json_value(&text) {
                        Some(json) => crate::tools::ToolResult::success(
                            serde_json::json!({ "subagentId": id, "result": json }).to_string(),
                        ),
                        None => crate::tools::ToolResult::error(format!(
                            "Sub-agent did not return a JSON value matching the requested schema.\n\nRaw output:\n{}",
                            text
                        )),
                    }
                } else {
                    crate::tools::ToolResult::success(
                        serde_json::json!({ "subagentId": id, "result": text }).to_string(),
                    )
                }
            }
            Err(e) => crate::tools::ToolResult::error(format!("Sub-agent failed: {:#}", e)),
        }
    }

    /// Spawn a continuable in-process sub-agent and run task, returning a
    /// (subagent_id, final_text) pair. The child is registered in this agent's
    /// live sub-agent registry so a later subagent_followup can continue it.
    /// Honors the delegation-depth bound (max_subagent_depth).
    pub(crate) async fn spawn_subagent_session(
        &self,
        task: &str,
        fork: bool,
    ) -> Result<(String, String)> {
        if self.delegation_depth >= self.max_subagent_depth {
            anyhow::bail!(
                "sub-agent depth limit reached ({}) — refusing to spawn deeper",
                self.max_subagent_depth
            );
        }
        {
            let reg = self.subagents.lock().await;
            if reg.len() >= self.max_subagents {
                anyhow::bail!(
                    "sub-agent quota reached ({}) — terminate one via subagent_terminate",
                    self.max_subagents
                );
            }
        }
        let mut child = Agent::new(
            self.config.clone(),
            self.project_dir.clone(),
            self.output.clone(),
            self.sandbox.clone(),
            self.plugin_manager.clone(),
        );
        child.delegation_depth = self.delegation_depth + 1;
        child.max_subagent_depth = self.max_subagent_depth;
        child.max_subagents = self.max_subagents;
        if fork {
            child.conversation = self.conversation.fork(self.conversation.log.len() as u64);
        }
        child.conversation.delegation_depth = child.delegation_depth;
        let id = format!("sa-{}", uuid::Uuid::new_v4());
        let child_arc = Arc::new(tokio::sync::Mutex::new(child));
        self.subagents.lock().await.insert(id.clone(), child_arc.clone());
        let text = {
            let mut guard = child_arc.lock().await;
            // Box the recursive call: process_message -> run_tool_loop -> spawn.
            Box::pin(guard.process_message(task)).await?
        };
        Ok((id, text))
    }

    /// Send a follow-up to a live sub-agent (by id) and return its next result.
    /// The sub-agent keeps its conversation, so this is multi-turn delegation.
    pub(crate) async fn subagent_followup(
        &self,
        id: &str,
        message: &str,
        output_schema: Option<&serde_json::Value>,
    ) -> crate::tools::ToolResult {
        let child = self.subagents.lock().await.get(id).cloned();
        match child {
            Some(child_arc) => {
                let result = {
                    let mut guard = child_arc.lock().await;
                    Box::pin(guard.process_message(message)).await
                };
                match result {
                    Ok(text) => {
                        if output_schema.is_some() {
                            match Self::extract_json_value(&text) {
                                Some(json) => crate::tools::ToolResult::success(
                                    serde_json::json!({ "subagentId": id, "result": json }).to_string(),
                                ),
                                None => crate::tools::ToolResult::error(format!(
                                    "Sub-agent did not return JSON matching the schema.\n\nRaw output:\n{}",
                                    text
                                )),
                            }
                        } else {
                            crate::tools::ToolResult::success(
                                serde_json::json!({ "subagentId": id, "result": text }).to_string(),
                            )
                        }
                    }
                    Err(e) => crate::tools::ToolResult::error(format!("Sub-agent follow-up failed: {:#}", e)),
                }
            }
            None => crate::tools::ToolResult::error(format!("unknown sub-agent id: {}", id)),
        }
    }
    /// Remove a live sub-agent from the registry, freeing its quota slot.
    pub(crate) async fn terminate_subagent(&self, id: &str) -> bool {
        self.subagents.lock().await.remove(id).is_some()
    }

    /// Best-effort extraction of a JSON value from sub-agent output. Try a direct
    /// parse of the trimmed text, then fall back to the first balanced {..} or [..]
    /// block (covers a model that wraps the JSON in prose).
    fn extract_json_value(text: &str) -> Option<serde_json::Value> {
        let t = text.trim();
        if let Ok(v) = serde_json::from_str::<serde_json::Value>(t) {
            return Some(v);
        }
        for open in ['{', '['] {
            if let Some(start) = t.find(open) {
                let close = if open == '{' { '}' } else { ']' };
                if let Some(end_rel) = t[start..].rfind(close) {
                    let end = start + end_rel + 1;
                    if let Ok(v) = serde_json::from_str::<serde_json::Value>(&t[start..end]) {
                        return Some(v);
                    }
                }
            }
        }
        None
    }


    /// 发射 `router.decision` intercepting hook，允许插件覆盖路由模式。
    /// 脚本失败/超时均回退为原模式，不阻断主流程。
    async fn apply_router_hook(
        &self,
        mode: crate::router::ExecutionMode,
        user_input: &str,
    ) -> crate::router::ExecutionMode {
        use crate::router::ExecutionMode;
        use crate::plugin::hook_bus::{HookEvent, HookResult};

        let bus = match &self.hook_bus {
            Some(b) => b.clone(),
            None => return mode,
        };

        let mode_str = match mode {
            ExecutionMode::BasicLoop => "basic_loop",
        };
        let classification_source = if self.force_mode.is_some() { "forced" } else { "auto" };
        let task_preview: String = user_input.chars().take(200).collect();

        let event = HookEvent::new(
            "router.decision",
            self.session_id.as_deref().unwrap_or("none").to_string(),
            serde_json::json!({
                "proposed_mode":        mode_str,
                "classification_source": classification_source,
                "task_preview":          task_preview,
            }),
        );

        match bus.emit_intercepting(event).await {
            HookResult::PatchParams { params } => {
                let override_str = params
                    .get("override_mode")
                    .and_then(|v| v.as_str())
                    .unwrap_or("");
                let new_mode = match override_str {
                    "basic_loop" => ExecutionMode::BasicLoop,
                    other => {
                        self.output.on_warning(&format!(
                            "[hook] router.decision: unknown override_mode '{}', keeping '{}'",
                            other, mode_str
                        ));
                        return mode;
                    }
                };
                if new_mode != mode {
                    let new_str = match new_mode {
                        ExecutionMode::BasicLoop => "basic_loop",
                    };
                    self.output.on_warning(&format!(
                        "🔀 Router overridden by hook: {} → {}",
                        mode_str, new_str
                    ));
                }
                new_mode
            }
            // Cancel / Approved 不阻断路由，降级为原决策
            HookResult::Cancel { reason } => {
                self.output.on_warning(&format!(
                    "[hook] router.decision cancelled ({}), keeping '{}'",
                    reason, mode_str
                ));
                mode
            }
            HookResult::Approved { .. } | HookResult::Continue => mode,
        }
    }

    /// Generate a brief explanation of what a tool is about to do and answer
    /// the user's question. Uses a lightweight LLM call (no tools).

    /// Query the hook system to see if a confirmation should be auto-approved,
    /// auto-denied, or left to the normal UI flow.
    ///
    /// Returns:
    ///   `Some(true)`  — hook approved; skip UI prompt
    ///   `Some(false)` — hook denied;   skip UI prompt
    ///   `None`        — no hook verdict; fall through to normal UI

    // ── Unified tool loop ─────────────────────────────────────────────────

    /// The unified tool loop that powers `process_message`.
    ///
    /// Each caller selects the subset of features via `opts` while the core
    /// LLM→tools→results→context cycle is shared.

    /// Process a user message and return the final text response.
    /// This handles the full agent loop: send message → receive response →
    /// if tool use → execute tools → send results → repeat until done.
    pub async fn process_message(&mut self, user_input: &str) -> Result<String> {
        // ── Router decision hook ─────────────────────────────────────────
        // Emit the (retired) router.decision hook so plugins can still observe
        // / override the mode, then fall through to the basic loop. Only
        // basic_loop is meaningful now; planning is driven by plan_mode.
        let mode = self.resolve_execution_mode(user_input).await;
        let _ = self.apply_router_hook(mode, user_input).await;

        // Prepend relevant memory context — used by all execution modes.
        let recall = self.memory.recall_relevant(user_input);
        let mut enriched_input = if recall.is_empty() {
            user_input.to_string()
        } else {
            format!("{}\n\n{}", recall, user_input)
        };


        // ── Sync global interrupt to per-session flag ─────────────────────
        // If a Ctrl-C happened before this turn started, propagate it to our
        // session flag and clear the global so we don't see it again next time.
        if is_interrupted() {
            self.request_interrupt();
            clear_interrupt();
        }

        // ── Reset loop detection counters for new turn ──────────────────
        self.turn_tool_call_hashes.clear();
        self.turns_without_mutation = 0;
        // Note: identical_tool_turns and prev_turn_hashes are NOT reset here
        // — they track patterns *across* turns, not within a single turn.

        // ── Turn start: notify memory providers ─────────────────────────
        self.total_turns += 1;
        self.conversation.append_turn_start(self.total_turns as u64);
        let max_tokens = self.context_engine.max_context_tokens(&self.config.model);
        let used_tokens = context::estimate_conversation_tokens(&self.conversation);
        let remaining_tokens = max_tokens.saturating_sub(used_tokens) as u64;
        self.memory.on_turn_start(
            self.total_turns as u32,
            user_input,
            remaining_tokens,
            &self.config.model,
        );

        if self.plan_mode {
            enriched_input = format!(
                "{}

[PLAN MODE GUIDANCE]
{}",
                plan_mode::plan_mode_guidance(),
                enriched_input
            );
        }

        // Add (already enriched) user message
        self.conversation.add_message(Message::user(&enriched_input));

        // Check context window before sending
        self.check_and_manage_context().await;

        let tool_defs = if self.plan_mode {
            confirmation::with_ask_user(
                plan_mode::plan_mode_toolset(self.tool_executor.readonly_definitions()),
            )
        } else {
            let mut defs = confirmation::with_ask_user(self.tool_executor.definitions());
            defs.push(plan_mode::subagent_definition());
            defs.push(plan_mode::subagent_fork_definition());
            defs.push(plan_mode::subagent_followup_definition());
            defs.push(plan_mode::subagent_terminate_definition());
            defs
        };

        // Per-turn tracking for record_interaction (zero extra LLM calls)
        let turn_start_tokens = self.total_input_tokens + self.total_output_tokens;
        let msg_count_before = self.conversation.messages.len();

        let opts = ToolLoopOptions {
            role: "agent".to_string(),
            enable_guardrails: true,
            enable_guidance: false,
            notify_file_created: true,
            handle_upload_image: true,
        };

        // Temporarily take ownership of the conversation so we can pass
        // a `&mut Conversation` to `run_tool_loop` without conflicting with
        // the `&mut self` borrow also required by that method.
        let mut conversation =
            std::mem::replace(&mut self.conversation, Conversation::new(&self.project_dir));
        let mut final_text = self
            .run_tool_loop(&mut conversation, &tool_defs, &opts)
            .await?;
        self.conversation = conversation;
        self.conversation.append_turn_end(self.total_turns as u64);
        if !self.conversation.log_is_consistent() {
            tracing::warn!(
                "[phase4] turn {} ended with a session log that diverged from the message surface;                  the log is authoritative and will be used on persistence",
                self.total_turns
            );
        }

        // If run_tool_loop returned empty (e.g. loop exhausted), fall back to
        // scanning the conversation for the last assistant text.
        if final_text.is_empty() {
            final_text = self
                .conversation
                .messages
                .iter()
                .rev()
                .find(|m| m.role == crate::conversation::Role::Assistant)
                .map(|m| m.text_content())
                .unwrap_or_default();
        }

        // Derive turn_tools_used and turn_had_errors from the messages added
        // during this turn (scanned from the conversation).
        // NOTE: msg_count_before may exceed current len if run_tool_loop
        // internally truncated the conversation (e.g. context compression).
        let start_idx = msg_count_before.min(self.conversation.messages.len());
        let new_msgs = &self.conversation.messages[start_idx..];
        let mut turn_tools_used: Vec<String> = Vec::new();
        let mut turn_had_errors = false;
        for msg in new_msgs {
            for block in &msg.content {
                if let ContentBlock::ToolUse { name, .. } = block {
                    turn_tools_used.push(name.clone());
                }
                if let ContentBlock::ToolResult { is_error, .. } = block {
                    if is_error.unwrap_or(false) {
                        turn_had_errors = true;
                    }
                }
            }
        }

        // Periodic knowledge extraction: every 5 turns, silently distill facts.
        self.knowledge_extract_turns += 1;
        if self.knowledge_extract_turns % 5 == 0 {
            self.extract_and_store_knowledge().await;
        }

        // Periodic diagnostics: every 10 turns, log conversation stats so we
        // can correlate hook-script timeouts with memory / context growth.
        if self.knowledge_extract_turns % 10 == 0 {
            let msg_count = self.conversation.messages.len();
            let token_est = context::estimate_conversation_tokens(&self.conversation);
            let mem_est: usize = self.conversation.messages.iter()
                .map(|m| m.content.iter().map(|b| match b {
                    ContentBlock::Text { text } => text.len(),
                    ContentBlock::ToolResult { content, .. } => content.len(),
                    ContentBlock::Thinking { thinking, .. } => thinking.len(),
                    _ => 256,
                }).sum::<usize>())
                .sum();
            tracing::info!(
                "[diag] turn={} messages={} tokens_est={} mem_est_bytes={} mem_est_mb={:.1}",
                self.total_turns,
                msg_count,
                token_est,
                mem_est,
                mem_est as f64 / 1_048_576.0,
            );
        }

        // Record complete interaction episode to intelligent memory.
        // intent_summary = first sentence of the assistant reply (zero extra tokens).
        let intent_summary = {
            let text = final_text.trim();
            text.split(['.', '\n', '\u{3002}']) // '。' for CJK
                .next()
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
                .unwrap_or_else(|| text.chars().take(120).collect())
        };
        let turn_tokens = ((self.total_input_tokens + self.total_output_tokens)
            .saturating_sub(turn_start_tokens)) as u32;
        let (outcome_ok, outcome_detail) = if turn_had_errors {
            (false, "One or more tool calls encountered errors".to_string())
        } else {
            (true, intent_summary.clone())
        };
        self.memory.record_interaction(
            user_input,
            &intent_summary,
            &turn_tools_used,
            outcome_ok,
            &outcome_detail,
            &[], // lessons extracted separately by extract_and_store_knowledge
            None,
            turn_tokens,
        );

        Ok(final_text)
    }

    // ── Knowledge extraction ──────────────────────────────────────────────────

    /// Extract project facts from the recent conversation and store them in memory.
    ///
    /// Called automatically every 5 turns inside `process_message`. Uses a
    /// `SilentOutput` so it produces no visible output.
    async fn extract_and_store_knowledge(&self) {
        // Collect the last 10 messages as source material
        let msgs = &self.conversation.messages;
        let window: Vec<_> = msgs.iter().rev().take(10).collect();
        if window.is_empty() {
            return;
        }

        let mut context = String::new();
        for msg in window.into_iter().rev() {
            let role = match msg.role {
                Role::User      => "User",
                Role::Assistant => "Assistant",
                Role::System    => continue,
            };
            context.push_str(&format!("{}: {}\n", role, msg.text_content()));
        }

        let prompt = format!(
            "From the conversation below, extract 1-3 concise project facts worth \
            remembering across sessions. Only facts that are durable (architecture, \
            file locations, key decisions, recurring patterns). \
            Return ONLY a bullet list with no preamble: one fact per line starting with `-`.\n\n{}",
            context
        );

        let mut conv = Conversation::new(&self.project_dir);
        conv.system_prompt = "You are a knowledge extractor. Be concise.".to_string();
        conv.add_message(Message::user(&prompt));

        let silent = Arc::new(SilentOutput) as Arc<dyn AgentOutput>;
        let cfg = self.role_configs.get("summarizer").unwrap_or(&self.config);
        let result = match cfg.provider {
            Provider::Anthropic =>
                streaming::stream_anthropic_response(cfg, &conv, &[], &*silent).await,
            Provider::OpenAI | Provider::Compatible =>
                streaming::stream_openai_response(cfg, &conv, &[], &*silent).await,
        };

        if let Ok(response) = result {
            let text: String = response.content.iter()
                .filter_map(|b| if let ContentBlock::Text { text } = b { Some(text.as_str()) } else { None })
                .collect();
            let facts: Vec<String> = text.lines()
                .map(|l| l.trim().trim_start_matches('-').trim().to_string())
                .filter(|l| l.len() > 10)
                .take(3)
                .collect();
            if !facts.is_empty() {
                self.memory.record_event(crate::memory::MemoryEvent::KnowledgeExtracted { facts });
            }
        }
    }

    /// Manually consolidate memory: read recent session log and all existing knowledge,
    /// ask LLM to distill into improved knowledge entries and compress the log.
    ///
    /// Called by the `/consolidate` CLI command.
    pub async fn consolidate_memory(&self) -> anyhow::Result<usize> {
        let existing_knowledge = self.memory.knowledge();
        let session_log = self.memory.session_log();

        if session_log.is_empty() && existing_knowledge.is_empty() {
            return Ok(0);
        }

        let mut prompt = String::from(
            "You are distilling an AI agent's memory. \
            Given the session log and existing knowledge below, \
            produce an improved, deduplicated list of up to 10 project knowledge facts.\n\
            Rules: each fact must be a single sentence, durable across sessions, \
            no timestamps, no trivial observations.\n\
            Return ONLY the bullet list starting each line with `-`.\n\n"
        );

        if !existing_knowledge.is_empty() {
            prompt.push_str("## Existing Knowledge\n");
            for k in &existing_knowledge {
                prompt.push_str(&format!("- {}\n", k));
            }
        }
        if !session_log.is_empty() {
            prompt.push_str("\n## Session Log (most recent activity)\n");
            for entry in session_log.iter().rev().take(30) {
                prompt.push_str(&format!("- {}\n", entry));
            }
        }

        let mut conv = Conversation::new(&self.project_dir);
        conv.system_prompt = "You are a memory consolidation assistant.".to_string();
        conv.add_message(Message::user(&prompt));

        let silent = Arc::new(SilentOutput) as Arc<dyn AgentOutput>;
        let cfg = self.role_configs.get("summarizer").unwrap_or(&self.config);
        let response = match cfg.provider {
            Provider::Anthropic =>
                streaming::stream_anthropic_response(cfg, &conv, &[], &*silent).await?,
            Provider::OpenAI | Provider::Compatible =>
                streaming::stream_openai_response(cfg, &conv, &[], &*silent).await?,
        };

        let text: String = response.content.iter()
            .filter_map(|b| if let ContentBlock::Text { text } = b { Some(text.as_str()) } else { None })
            .collect();

        let facts: Vec<String> = text.lines()
            .map(|l| l.trim().trim_start_matches('-').trim().to_string())
            .filter(|l| l.len() > 10)
            .take(10)
            .collect();

        let count = facts.len();
        if count > 0 {
            self.memory.record_event(crate::memory::MemoryEvent::KnowledgeExtracted { facts });
        }
        Ok(count)
    }

