/// Build a per-role Config map from the loaded models.toml.
///
/// For every entry in `[roles]` that references a valid model alias,
/// we pre-build a `Config` so callers can just do `role_configs["planner"]`
/// without repeating resolution logic.
fn build_role_configs(
    base: &Config,
    models_cfg: &model_manager::ModelsConfig,
) -> HashMap<String, Config> {
    let mut map = HashMap::new();
    for (role_name, role_cfg) in &models_cfg.roles {
        let config = base.for_role(role_name, models_cfg);
        // If system_prompt is set inline, we store it in the role entry; here
        // we only care about which model/provider/key to call.
        let _ = &role_cfg.system_prompt; // acknowledged, used later
        map.insert(role_name.clone(), config);
    }
    map
}